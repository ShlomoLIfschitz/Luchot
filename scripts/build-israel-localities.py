"""Generate src/constants/israelLocalities.ts from the CBS localities file.

Source: Israel Central Bureau of Statistics, "קובץ יישובים" (bycode<year>.xlsx),
https://www.cbs.gov.il/he/publications/doclib/2019/ishuvim/bycode2024.xlsx

Kept (Shlomo, 2026-11-22: "רק רשימה של ערים וישובים יהודיים או ערים מעורבות"):
  - "דת יישוב" 1 (Jewish) and 4 (mixed: Jerusalem, Tel Aviv-Yafo, Haifa, Acre,
    Lod, Ramla, Ma'alot-Tarshiha, Nof HaGalil, Neve Shalom);
  - rows with no religion code whose "צורת יישוב" is 510 (new localities CBS
    has no population for yet), minus army camps (names ending in "*");
  - the Dead Sea hotels area ("ים המלח - בתי מלון").
Rows without coordinates are dropped. Sorted by 2024 population, largest first,
so the picker shows the big cities on top before the user types.

Coordinates are ITM (Israel 1993 / Israeli TM Grid, EPSG:2039). They are
converted to latitude/longitude with the inverse transverse Mercator on GRS80;
the Israel 1993 -> WGS84 datum shift (tens of metres) is ignored: 1 km moves
sunset by about 4 seconds.

Usage (needs openpyxl):
  python scripts/build-israel-localities.py <bycode2024.xlsx>
"""
import math
import sys
from pathlib import Path

import openpyxl

OUT = Path(__file__).resolve().parent.parent / 'src' / 'constants' / 'israelLocalities.ts'

# EPSG:2039 parameters (GRS80 ellipsoid)
A = 6378137.0
F = 1 / 298.257222101
LAT0 = math.radians(31.7343936111111)
LON0 = math.radians(35.2045169444444)
K0 = 1.0000067
FE = 219529.584
FN = 626907.390


def _meridian_arc(phi: float) -> float:
    e2 = F * (2 - F)
    e4, e6 = e2 * e2, e2 * e2 * e2
    return A * ((1 - e2 / 4 - 3 * e4 / 64 - 5 * e6 / 256) * phi
                - (3 * e2 / 8 + 3 * e4 / 32 + 45 * e6 / 1024) * math.sin(2 * phi)
                + (15 * e4 / 256 + 45 * e6 / 1024) * math.sin(4 * phi)
                - (35 * e6 / 3072) * math.sin(6 * phi))


def itm_to_latlng(e: float, n: float) -> tuple[float, float]:
    e2 = F * (2 - F)
    ep2 = e2 / (1 - e2)
    m = _meridian_arc(LAT0) + (n - FN) / K0
    mu = m / (A * (1 - e2 / 4 - 3 * e2 ** 2 / 64 - 5 * e2 ** 3 / 256))
    e1 = (1 - math.sqrt(1 - e2)) / (1 + math.sqrt(1 - e2))
    phi1 = (mu + (3 * e1 / 2 - 27 * e1 ** 3 / 32) * math.sin(2 * mu)
            + (21 * e1 ** 2 / 16 - 55 * e1 ** 4 / 32) * math.sin(4 * mu)
            + (151 * e1 ** 3 / 96) * math.sin(6 * mu)
            + (1097 * e1 ** 4 / 512) * math.sin(8 * mu))
    s, c, t = math.sin(phi1), math.cos(phi1), math.tan(phi1)
    c1 = ep2 * c * c
    t1 = t * t
    n1 = A / math.sqrt(1 - e2 * s * s)
    r1 = A * (1 - e2) / (1 - e2 * s * s) ** 1.5
    d = (e - FE) / (n1 * K0)
    lat = phi1 - (n1 * t / r1) * (d ** 2 / 2 - (5 + 3 * t1 + 10 * c1 - 4 * c1 ** 2 - 9 * ep2) * d ** 4 / 24
                                  + (61 + 90 * t1 + 298 * c1 + 45 * t1 ** 2 - 252 * ep2 - 3 * c1 ** 2) * d ** 6 / 720)
    lng = LON0 + (d - (1 + 2 * t1 + c1) * d ** 3 / 6
                  + (5 - 2 * c1 + 28 * t1 - 3 * c1 ** 2 + 8 * ep2 + 24 * t1 ** 2) * d ** 5 / 120) / c
    return math.degrees(lat), math.degrees(lng)


def clean_name(name: str) -> str:
    # CBS writes "תל אביב -יפו"; close a one-sided space around a hyphen,
    # keep a spaced dash ("ים המלח - בתי מלון").
    name = ' '.join(str(name).split()).replace(' - ', '|')
    return name.replace(' -', '-').replace('- ', '-').replace('|', ' - ')


def keep(row: dict) -> bool:
    religion = row['דת יישוב']
    name = str(row['שם יישוב'])
    if religion in (1, 4):
        return True
    if religion is None and row['צורת יישוב שוטפת'] == 510 and not name.endswith('*'):
        return True
    return name == 'ים המלח - בתי מלון'


def main(path: str) -> None:
    ws = openpyxl.load_workbook(path, read_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    header = rows[0]
    out = []
    for raw in rows[1:]:
        row = dict(zip(header, raw))
        if not row['שם יישוב'] or not row['קואורדינטות'] or not keep(row):
            continue
        coords = str(row['קואורדינטות']).zfill(12)
        lat, lng = itm_to_latlng(float(coords[:6]), float(coords[6:]))
        out.append({
            'code': int(row['סמל יישוב']),
            'he': clean_name(row['שם יישוב']),
            'en': ' '.join(str(row['שם יישוב באנגלית'] or '').split()),
            'lat': round(lat, 4),
            'lng': round(lng, 4),
            'pop': int(row['סך הכל אוכלוסייה 2024'] or 0),
        })
    out.sort(key=lambda r: (-r['pop'], r['he']))

    def js(s: str) -> str:
        return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

    lines = [
        '// src/constants/israelLocalities.ts',
        '//',
        '// GENERATED by scripts/build-israel-localities.py from the CBS localities',
        '// file (bycode2024.xlsx). Do not edit by hand; re-run the script.',
        '// Jewish and mixed localities only, largest population first.',
        '',
        'export interface IsraelLocality {',
        '  code: number; // CBS locality code (סמל יישוב)',
        '  he: string;',
        '  en: string;',
        '  lat: number;',
        '  lng: number;',
        '}',
        '',
        f'// {len(out)} localities',
        'export const ISRAEL_LOCALITIES: IsraelLocality[] = [',
    ]
    for r in out:
        lines.append(f"  {{ code: {r['code']}, he: {js(r['he'])}, en: {js(r['en'])}, lat: {r['lat']}, lng: {r['lng']} }},")
    lines += ['];', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {len(out)} localities to {OUT}')


if __name__ == '__main__':
    main(sys.argv[1])
